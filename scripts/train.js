// Tunes each system's alert threshold, then trains the final classifier.
//
//   node scripts/train.js  ->  src/model.js, results/thresholds.json
//
// 1. Tuning: a temporary classifier is fitted on scam calls built from half the
//    training phrasings plus everyday speech. Thresholds are tuned on scam calls
//    built from the other half and on all genuine training calls, none of which
//    that classifier has seen. So the threshold reflects unfamiliar wording.
// 2. Final model: the classifier is retrained on every training call.
// Test calls and hand-written calls are never used here.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { train } from "../src/classifier.js";
import { EVERYDAY } from "../data/phrases.js";
import { SYSTEMS, tuneThreshold, tuneSatark } from "../src/evaluate.js";
import { noisyCalls } from "../src/noise.js";

const data = JSON.parse(readFileSync(new URL("../data/calls.json", import.meta.url)));
const toExamples = (calls) => calls.flatMap((c) => c.lines.map((l) => ({ text: l[1], label: l[2] || "none" })));
const everyday = EVERYDAY.map((text) => ({ text, label: "none" }));

// 1. Tune thresholds on unfamiliar wording.
const tuneModel = train([...toExamples(data.tuneFit), ...everyday]);
// Live microphones make recognition errors, so half the validation calls are noisy.
const clean = [...data.tuneVal, ...data.train.filter((c) => c.label === "genuine")];
const validation = [...clean, ...noisyCalls(clean, 99)];
const thresholds = {};
for (const [key, system] of Object.entries(SYSTEMS)) {
  if (system.keyword) continue;
  if (key === "satark") {
    const best = tuneSatark(validation, tuneModel);
    thresholds[key] = { threshold: best.threshold, modelWeight: best.modelWeight };
  } else {
    thresholds[key] = { threshold: tuneThreshold(validation, tuneModel, system).threshold };
  }
}

// 2. Train the final classifier on all training calls.
const examples = [...toExamples(data.train), ...everyday];
const model = train(examples);
writeFileSync(
  new URL("../src/model.js", import.meta.url),
  `// Generated by scripts/train.js. Do not edit.\nexport default ${JSON.stringify(model)};\n`,
);
mkdirSync(new URL("../results/", import.meta.url), { recursive: true });
writeFileSync(new URL("../results/thresholds.json", import.meta.url), JSON.stringify(thresholds, null, 2) + "\n");

console.log(`final classifier: ${examples.length} lines from ${data.train.length} calls, ${model.vocabSize} features`);
console.log(`thresholds tuned on ${validation.length} unfamiliar calls:`, thresholds);
